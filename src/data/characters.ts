export function getCharacter(id: string): CharacterDef | undefined {
  return CHARACTERS.find((c) => c.id === id)
}

/** 把角色网格按缩放倍数画成透明底画布（scale=16 → 320×320，可直接喂给 pixelate） */
export function drawCharacter(def: CharacterDef, scale = 1): HTMLCanvasElement {
  const size = def.grid.length
  const c = document.createElement('canvas')
  c.width = size * scale
  c.height = size * scale
  const ctx = c.getContext('2d')
  if (!ctx) return c
  for (let y = 0; y < size; y++) {
    const row = def.grid[y].padEnd(size, '.')
    for (let x = 0; x < size; x++) {
      const color = def.colors[row[x]]
      if (!color) continue
      ctx.fillStyle = color
      ctx.fillRect(x * scale, y * scale, scale, scale)
    }
  }
  return c
}
